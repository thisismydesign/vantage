// Writes 10_prices.sql: a year of daily closes for the seeded holdings, keyed
// by the broker's symbol, and each currency's rate to EUR. The seed shifts the
// dates to end near today, so this only needs re-running to refresh the shape.
//
//   node supabase/seed/prices.ts

import { writeFile } from "node:fs/promises";

/** Broker symbol → Yahoo symbol. GBp quotes are scaled to pounds. */
const SYMBOLS: Record<string, string> = {
  MU: "MU",
  NVDA: "NVDA",
  GOOG: "GOOG",
  TSLA: "TSLA",
  LITE: "LITE",
  COHR: "COHR",
  AAOI: "AAOI",
  MSFT: "MSFT",
  NET: "NET",
  CRWD: "CRWD",
  SOI: "SOI.PA",
  IQEl: "IQE.L",
};
/** Currency → Yahoo pair quoting it per EUR; the seed stores the inverse. */
const RATES: Record<string, string> = { USD: "EURUSD=X", GBP: "EURGBP=X" };

async function closes(symbol: string): Promise<[string, number][]> {
  const url = `https://query2.finance.yahoo.com/v8/finance/chart/${encodeURIComponent(symbol)}?range=1y&interval=1d`;
  const response = await fetch(url, {
    headers: { "User-Agent": "Mozilla/5.0 (compatible; vantage)" },
  });
  if (!response.ok) throw new Error(`${symbol}: Yahoo responded ${response.status}`);
  const result = (await response.json()).chart.result[0];
  const scale = result.meta.currency === "GBp" ? 0.01 : 1;
  const close: (number | null)[] = result.indicators.quote[0].close;
  return (result.timestamp as number[]).flatMap((t, i) =>
    close[i] == null ? [] : [[new Date(t * 1000).toISOString().slice(0, 10), close[i]! * scale]],
  );
}

const rows: string[] = [];
for (const [symbol, yahoo] of Object.entries(SYMBOLS))
  for (const [day, close] of await closes(yahoo))
    rows.push(`('${symbol}','${day}',${close.toFixed(4)})`);
for (const [currency, yahoo] of Object.entries(RATES))
  for (const [day, close] of await closes(yahoo))
    rows.push(`('${currency}','${day}',${(1 / close).toFixed(6)})`);

const sql = `-- Generated by prices.ts from Yahoo Finance on ${new Date().toISOString().slice(0, 10)}. Do not edit.
-- Daily closes per broker symbol in its listing currency; currency rows are EUR per unit.
-- One block: the CLI sends a seed file as one batch.
do $prices$
begin
create schema seed;
create table seed.prices (symbol text, day date, close numeric, primary key (symbol, day));
insert into seed.prices (symbol, day, close) values
${rows.join(",\n")}
on conflict do nothing;
end;
$prices$;
`;
await writeFile(new URL("10_prices.sql", import.meta.url), sql);
console.log(`${rows.length} closes`);
