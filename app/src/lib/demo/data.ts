const DAY_MS = 86_400_000;
const pad = (n: number) => String(n).padStart(2, "0");
/** The local calendar day of `d`, as YYYY-MM-DD. */
export const localDay = (d: Date) =>
  `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;
export const addDays = (day: string, n: number) =>
  new Date(Date.parse(day) + n * DAY_MS).toISOString().slice(0, 10);
/** The last Friday before `today` (YYYY-MM-DD). */
export function statementDay(today: string) {
  const weekday = new Date(Date.parse(today)).getUTCDay();
  return addDays(today, -((weekday + 2) % 7 || 7));
}

