const round2 = (n: number) => Math.round(n * 100) / 100;
const deposited = (keep: (day: number) => boolean) =>
  DEMO_DEPOSITS.filter(([day]) => keep(day)).reduce((sum, [, amount]) => sum + amount, 0);

/** The demo account as table rows, without `owner`, dated around `now`. */
export function demoRows(now: Date) {
  const today = localDay(now);
  const asOf = statementDay(today);
  const account = { account_id: DEMO_ACCOUNT };
  return {
    ...demoList(),
    fills: DEMO_FILLS.map((f) => {
      const proceeds = round2(-f.quantity * f.price);
      return {
        id: f.id,
        traded_at: `${addDays(asOf, f.day)}T${f.time}`,
        ...account,
        conid: f.conid,
        order_id: f.id,
        symbol: f.symbol,
        description: f.description,
        asset_category: "STK",
        currency: f.currency,
        side: f.quantity > 0 ? ("buy" as const) : ("sell" as const),
        quantity: f.quantity,
        price: f.price,
        multiplier: 1,
        proceeds,
        commission: f.commission,
        net_cash: round2(proceeds + f.commission),
        fx_rate_to_base: f.fx,
        broker_pnl: f.pnl,
        open_close: f.openClose,
      };
    }),
    snapshot: {
      as_of: asOf,
      ...account,
      base_currency: DEMO_BASE_CURRENCY,
      nav: DEMO_NAV,
      cash: DEMO_CASH,
      // Statements arrive the morning after.
      fetched_at: `${addDays(asOf, 1)}T06:00:00+00:00`,
    },
    positions: DEMO_POSITIONS.map((p) => ({
      as_of: asOf,
      ...account,
      symbol: p.symbol,
      description: p.description,
      asset_category: "STK",
      currency: p.currency,
      quantity: p.quantity,
      mark_price: p.mark,
      position_value: round2(p.quantity * p.mark),
      cost_basis: p.cost,
      unrealized_pnl: round2(p.quantity * p.mark - p.cost),
      fx_rate_to_base: p.fx,
    })),
    nav: DEMO_NAV_HISTORY.map(([day, nav, cash]) => ({
      as_of: addDays(asOf, day),
      ...account,
      base_currency: DEMO_BASE_CURRENCY,
      nav: round2(nav + deposited((d) => d <= day)),
      cash: round2(cash + deposited((d) => d <= day)),
      flow: deposited((d) => d === day),
    })),
    events: DEMO_EVENTS.map((e, i) => ({
      ticker: e.ticker,
      category: e.category,
      kind: e.kind,
      title: e.title,
      description: e.description,
      starts_on: addDays(today, e.starts),
      ends_on: e.ends === null ? null : addDays(today, e.ends),
      estimated: e.estimated,
      external_id: `demo-event-${i + 1}`,
    })),
    news: DEMO_NEWS.map((n, i) => ({
      ticker: n.ticker,
      published_at: new Date(now.getTime() - n.hoursAgo * 3_600_000).toISOString(),
      title: n.title,
      description: n.description,
      sentiment: n.sentiment,
      expected: n.expected,
      external_id: `demo-news-${i + 1}`,
    })),
  };
}
